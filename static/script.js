async function downloadText() {
    const { jsPDF } = window.jspdf;

    const text = document.getElementById("output").innerText;
    const fileInput = document.getElementById("audioUpload");

    if (!text || text === "⏳ Processing...") {
        alert("No transcript available!");
        return;
    }

    let fileName = "transcript";

    if (fileInput.files.length > 0) {
        const originalName = fileInput.files[0].name;
        fileName = originalName.split('.')[0];
    }

    const doc = new jsPDF();

    // 🎨 HEADER BACKGROUND
    doc.setFillColor(41, 128, 185); // blue
    doc.rect(0, 0, 210, 30, "F");

    // 🧾 TITLE
    doc.setTextColor(255, 255, 255);
    doc.setFontSize(18);
    doc.setFont(undefined, "bold");
    doc.text("MedVoice AI", 20, 15);

    doc.setFontSize(12);
    doc.text("Medical Transcription Report", 20, 23);

    // RESET COLOR
    doc.setTextColor(0, 0, 0);

    // 📅 DATE + AUDIO
    doc.setFontSize(11);
    doc.setFont(undefined, "bold");
    doc.text("Date:", 20, 45);
    doc.text(new Date().toLocaleString(), 60, 45);

    doc.setFont(undefined, "bold");
    doc.text("Audio File:", 20, 55);
    doc.text(fileName, 60, 55);

    // 📦 BOX FOR TRANSCRIPTION
    doc.setDrawColor(200);
    doc.roundedRect(15, 65, 180, 100, 5, 5);

    // 🧠 SECTION TITLE
    doc.setFontSize(14);
    doc.setFont(undefined, "bold");
    doc.text("Transcription", 20, 75);

    // 📄 CONTENT
    doc.setFontSize(11);
    doc.setFont(undefined, "normal");

    const splitText = doc.splitTextToSize(text, 160);
    doc.text(splitText, 20, 85);

    // 🧾 FOOTER
    doc.setFontSize(9);
    doc.setTextColor(120);
    doc.text("Generated by MedVoice AI • AI-powered healthcare assistant", 105, 285, { align: "center" });

    doc.save(fileName + "_report.pdf");
}